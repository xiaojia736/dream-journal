/// A date-seeded shuffle: one local calendar day, one offline reflection.
/// 17 is coprime to the 31-item library, so each 31-day cycle uses every quote.
String dailyQuote(DateTime date) {
  final calendarDay = DateTime.utc(date.year, date.month, date.day);
  final dayNumber = calendarDay.millisecondsSinceEpoch ~/ Duration.millisecondsPerDay;
  final index = (dayNumber * 17 + 11) % dailyQuotes.length;
  return dailyQuotes[index];
}
